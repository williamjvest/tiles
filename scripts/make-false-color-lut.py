#!/usr/bin/env python3
"""Generate Tiles' false colour monitor LUT for Sony S-Log3 / S-Gamut3.Cine.

The app loads this onto a camera that has no false colour LUT (first empty User slot, never over one in use), so
every body gets the LUT tile's False Color switch, not only the ones somebody already loaded a LUT onto.

The mapping is LUTCalc's false colour (Ben Turley), as George Kamenov's GK SLog3 False Color LUTs use it: scene
luminance in stops from 18% grey picks a colour band, and everything else is shown as grey (the luminance, re-encoded in S-Log3 and
expanded from legal to full range, as that LUT does). The band edges were read from that LUT's grid; this script
computes the bands itself, so no third-party file ships with the app.

    purple   below -10 stops       black clip
    blue     -10 to -6.1 stops     just above black
    green    18% grey +-0.2 stop
    pink     +1 stop +-0.17
    yellow   +5.5 to +6 stops      just under clip
    red      +6 stops and up       clipped

Usage: scripts/make-false-color-lut.py [output.cube] [--compare reference.cube]
"""
import math
import sys

SIZE = 33  # the FX3 takes 17- or 33-point cubes

# S-Gamut3.Cine luminance: the Y row of its RGB -> XYZ matrix, from its primaries and D65 white.
def _luminance_coefficients():
    def xyz(x, y):
        return [x / y, 1.0, (1 - x - y) / y]
    primaries = [xyz(0.766, 0.275), xyz(0.225, 0.800), xyz(0.089, -0.087)]
    white = xyz(0.3127, 0.3290)
    m = [[primaries[j][i] for j in range(3)] for i in range(3)]

    def det(a):
        return (a[0][0] * (a[1][1] * a[2][2] - a[1][2] * a[2][1])
                - a[0][1] * (a[1][0] * a[2][2] - a[1][2] * a[2][0])
                + a[0][2] * (a[1][0] * a[2][1] - a[1][1] * a[2][0]))
    d = det(m)
    scale = []
    for k in range(3):
        mk = [row[:] for row in m]
        for i in range(3):
            mk[i][k] = white[i]
        scale.append(det(mk) / d)
    return [scale[j] * primaries[j][1] for j in range(3)]

Y_COEFFS = _luminance_coefficients()  # about [0.2151, 0.8851, -0.1001]

def slog3_to_linear(v):
    c = v * 1023
    if c >= 171.2102946929:
        return (10 ** ((c - 420) / 261.5)) * 0.19 - 0.01
    return (c - 95) * 0.01125 / (171.2102946929 - 95)

def linear_to_slog3(x):
    if x >= 0.01125:
        return (420 + math.log10((x + 0.01) / 0.19) * 261.5) / 1023
    return (x * (171.2102946929 - 95) / 0.01125 + 95) / 1023

PURPLE, BLUE, GREEN = (0.75, 0.0, 0.75), (0.0, 0.0, 0.75), (0.0, 0.7, 0.0)
PINK, YELLOW, RED = (0.75, 0.35, 0.35), (0.7, 0.7, 0.0), (0.75, 0.0, 0.0)

def false_colour(r, g, b):
    y = sum(c * slog3_to_linear(v) for c, v in zip(Y_COEFFS, (r, g, b)))
    stops = math.log2(y / 0.18) if y > 0 else -99.0
    if stops < -10.0:
        return PURPLE
    if stops < -6.1:
        return BLUE
    if -0.2 <= stops <= 0.2:
        return GREEN
    if 0.83 <= stops <= 1.17:
        return PINK
    if stops >= 6.0:
        return RED
    if stops >= 5.5:
        return YELLOW
    grey = min(1.0, max(0.0, (linear_to_slog3(y) * 1023 - 64) / 876))
    return (grey, grey, grey)

def build():
    rows = []
    for b in range(SIZE):
        for g in range(SIZE):
            for r in range(SIZE):
                rows.append(false_colour(r / (SIZE - 1), g / (SIZE - 1), b / (SIZE - 1)))
    return rows

def write(path, rows):
    with open(path, "w") as f:
        f.write('TITLE "TW False Color"\n')
        f.write("# TW CC false colour, S-Log3/S-Gamut3.Cine in. Monitoring only: don't bake it in.\n")
        f.write("# Generated by scripts/make-false-color-lut.py\n")
        f.write(f"LUT_3D_SIZE {SIZE}\n")
        for r, g, b in rows:
            f.write(f"{r:.4f} {g:.4f} {b:.4f}\n")

def read(path):
    rows = []
    for line in open(path):
        t = line.strip()
        if not t or t[0].isalpha() or t.startswith("#"):
            continue
        rows.append(tuple(float(x) for x in t.split()[:3]))
    return rows

if __name__ == "__main__":
    args = sys.argv[1:]
    reference = None
    if "--compare" in args:
        i = args.index("--compare")
        reference = args[i + 1]
        del args[i:i + 2]
    out = args[0] if args else "TW False Color SLog3.cube"
    rows = build()
    write(out, rows)
    print(f"wrote {out}: {len(rows)} points")
    if reference:
        ref = read(reference)
        worst = max(max(abs(a - b) for a, b in zip(p, q)) for p, q in zip(rows, ref))
        differ = sum(1 for p, q in zip(rows, ref) if max(abs(a - b) for a, b in zip(p, q)) > 0.01)
        print(f"vs {reference}: {differ} of {len(ref)} points differ by more than 0.01 (largest {worst:.3f})")
